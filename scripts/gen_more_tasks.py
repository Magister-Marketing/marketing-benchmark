CRAWL_UTILITY = [
    ("/cart", "Your Cart"), ("/checkout", "Checkout"), ("/account/login", "Sign In"),
    ("/account/register", "Create Account"), ("/search", "Search"), ("/wishlist", "Wishlist"),
]

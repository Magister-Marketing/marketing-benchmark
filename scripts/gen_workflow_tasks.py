#!/usr/bin/env python3
"""Write, or check, the files of the workflow tasks.

A workflow task's files (its export, its standard, its facts) are generated by
the same module that grades it (eval_runner/workflows/<task>.py), so a rule
cannot say one thing in the brief and another in the grader. This writes them
under eval_runner/fixtures/<task id>/.

    python3 scripts/gen_workflow_tasks.py --write   # (re)write every file
    python3 scripts/gen_workflow_tasks.py --check   # report drift, change nothing

Deterministic: running it twice writes the same bytes.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))
from eval_runner import workflows  # noqa: E402


def planned() -> dict[Path, str]:
    """Every generated file, by its path in the repository."""
    files: dict[Path, str] = {}
    for module in {workflows.module_for(workflow) for workflow in workflows.MODULES}:
        for name, text in module.fixtures().items():
            files[REPO_ROOT / module.FIXTURE_DIR / name] = text
    return files


def drift() -> list[str]:
    return [
        f"{path.relative_to(REPO_ROOT)}: {'missing' if not path.exists() else 'differs from what the module generates'}"
        for path, text in planned().items()
        if not path.exists() or path.read_text() != text
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.write:
        for path, text in planned().items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        print(f"wrote {len(planned())} file(s)")
        return 0
    problems = drift()
    for problem in problems:
        print(problem)
    print("ok" if not problems else f"{len(problems)} file(s) out of date: run with --write")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
